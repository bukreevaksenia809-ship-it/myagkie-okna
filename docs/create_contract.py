def set_cell_margins(cell, top=70, start=90, bottom=70, end=90):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcMar = tcPr.first_child_found_in("w:tcMar")
    if tcMar is None:
        tcMar = OxmlElement("w:tcMar")
        tcPr.append(tcMar)
    for tag, value in (("w:top", top), ("w:start", start), ("w:bottom", bottom), ("w:end", end)):
        node = tcMar.find(qn(tag))
        if node is None:
            node = OxmlElement(tag)
            tcMar.append(node)
        node.set(qn("w:w"), str(value))
        node.set(qn("w:type"), "dxa")


def shade(cell, hex_color):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), hex_color)
    tcPr.append(shd)


def set_repeat_table_header(row):
    trPr = row._tr.get_or_add_trPr()
    tblHeader = OxmlElement("w:tblHeader")
    tblHeader.set(qn("w:val"), "true")
    trPr.append(tblHeader)


def add_page_number(paragraph):
    run = paragraph.add_run()
    fldChar1 = OxmlElement("w:fldChar")
    fldChar1.set(qn("w:fldCharType"), "begin")
    instrText = OxmlElement("w:instrText")
    instrText.set(qn("xml:space"), "preserve")
    instrText.text = "PAGE"
    fldChar2 = OxmlElement("w:fldChar")
    fldChar2.set(qn("w:fldCharType"), "end")
    run._r.append(fldChar1)
    run._r.append(instrText)
    run._r.append(fldChar2)


def p(doc, text="", *, bold=False, italic=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
      space_before=0, space_after=4, first_line=None, keep=False, size=None):
    par = doc.add_paragraph()
    pf = par.paragraph_format
    pf.alignment = align
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing = 1.12
    if first_line is not None:
        pf.first_line_indent = Cm(first_line)
    if keep:
        pf.keep_with_next = True
    run = par.add_run(text)
    run.bold = bold
    run.italic = italic
    if size:
        run.font.size = Pt(size)
    return par


def rich(doc, parts, *, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_line=1.25,
         space_after=4, keep=False):
    par = doc.add_paragraph()
    pf = par.paragraph_format
    pf.alignment = align
    pf.space_before = Pt(0)
    pf.space_after = Pt(space_after)
    pf.line_spacing = 1.12
    pf.first_line_indent = Cm(first_line)
    if keep:
        pf.keep_with_next = True
    for text, bold in parts:
        run = par.add_run(text)
        run.bold = bold
    return par


def heading(doc, text, level=1):
    par = doc.add_paragraph()
    pf = par.paragraph_format
    pf.space_before = Pt(12 if level == 1 else 8)
    pf.space_after = Pt(5)
    pf.keep_with_next = True
    run = par.add_run(text)
    run.bold = True
    run.font.size = Pt(13 if level == 1 else 11.5)
    return par


def bullet(doc, text):
    par = doc.add_paragraph(style="List Bullet")
    par.paragraph_format.space_after = Pt(2)
    par.paragraph_format.line_spacing = 1.1
    par.add_run(text)
    return par


def set_col_widths(table, widths):
    table.autofit = False
    for row in table.rows:
        for idx, width in enumerate(widths):
            if idx < len(row.cells):
                row.cells[idx].width = Cm(width)


def table_header(table, labels, widths=None):
    hdr = table.rows[0].cells
    for idx, text in enumerate(labels):
        cell = hdr[idx]
        cell.text = ""
        pp = cell.paragraphs[0]
        pp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        pp.paragraph_format.space_after = Pt(0)
        r = pp.add_run(text)
        r.bold = True
        r.font.size = Pt(10)
        shade(cell, "E8EDF4")
        set_cell_margins(cell)
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
    set_repeat_table_header(table.rows[0])
    if widths:
        set_col_widths(table, widths)


